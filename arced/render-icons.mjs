// Generates the ARCED Android vector drawables from the SVGs in arced/brand/.
// Re-run after changing a brand SVG: node arced/render-icons.mjs
// Handles only what those SVGs use: <g>/<path>/<circle>, translate() and scale() transforms,
// fill, stroke, stroke-width and stroke-linecap.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = (name) => readFileSync(new URL(`arced/brand/${name}`, root), "utf8");
const write = (path, xml) => writeFileSync(new URL(path, root), xml);

const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
const circle = (cx, cy, r) =>
  `M${cx - r},${cy} A${r},${r} 0 1,0 ${cx + r},${cy} A${r},${r} 0 1,0 ${cx - r},${cy} Z`;

// "translate(a b) scale(s)" -> nested <group> open tags, outermost first.
function groups(transform) {
  if (!transform) return [];
  return [...transform.matchAll(/(translate|scale)\(([^)]*)\)/g)].map(([, op, args]) => {
    const [x, y = op === "scale" ? x : "0"] = args.trim().split(/[\s,]+/);
    return op === "translate"
      ? `<group android:translateX="${x}" android:translateY="${y}">`
      : `<group android:scaleX="${x}" android:scaleY="${y}">`;
  });
}

function pathXml(d, tag, colour) {
  const fill = attr(tag, "fill") === "none" ? null : (colour ?? attr(tag, "fill"));
  const stroke = attr(tag, "stroke");
  let xml = `<path android:pathData="${d}"`;
  if (fill) xml += ` android:fillColor="${fill}"`;
  if (stroke) {
    xml += ` android:strokeColor="${colour ?? stroke}"`;
    xml += ` android:strokeWidth="${attr(tag, "stroke-width") ?? 1}"`;
    const cap = attr(tag, "stroke-linecap");
    if (cap) xml += ` android:strokeLineCap="${cap}"`;
  }
  return xml + "/>";
}

// SVG body -> VectorDrawable body. `colour` forces one colour (monochrome icons).
function body(svg, colour) {
  let out = "";
  const open = []; // groups opened by each <g>, closed at its </g>
  for (const [tag] of svg.matchAll(/<\/?(g|path|circle)\b[^>]*>/g)) {
    if (tag.startsWith("</g")) {
      out += "</group>".repeat(open.pop());
      continue;
    }
    const wrap = groups(attr(tag, "transform"));
    if (tag.startsWith("<g")) {
      out += wrap.join("");
      open.push(wrap.length);
      continue;
    }
    const d = tag.startsWith("<circle")
      ? circle(+attr(tag, "cx"), +attr(tag, "cy"), +attr(tag, "r"))
      : attr(tag, "d");
    out += wrap.join("") + pathXml(d, tag, colour) + "</group>".repeat(wrap.length);
  }
  return out;
}

function vector(svg, { width, height, inner, colour }) {
  const [, , vw, vh] = attr(svg.match(/<svg[^>]*>/)[0], "viewBox").split(/\s+/).map(Number);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by arced/render-icons.mjs. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${width ?? +(height * (vw / vh)).toFixed(2)}dp"
    android:height="${height}dp"
    android:viewportWidth="${vw}"
    android:viewportHeight="${vh}">
${inner ? inner(body(svg, colour)) : body(svg, colour)}
</vector>
`;
}

// Login and registration wordmark: dark text by day, light text at night.
write("ui/src/main/res/drawable/logo_bitwarden.xml", vector(read("logo.svg"), { height: 45 }));
write(
  "ui/src/main/res/drawable-night/logo_bitwarden.xml",
  vector(read("logo-reversed.svg"), { height: 45 }),
);

// Autofill suggestion and credential exchange icon: the rounded app icon.
write(
  "ui/src/main/res/drawable/logo_bitwarden_icon.xml",
  vector(read("app-icon.svg"), { width: 1024, height: 1024 }),
);

// Adaptive launcher foreground (also the splash icon). The symbol is scaled to 75 % around the
// centre of a 512 canvas, so its corners stay inside the 72 dp visible circle of a round mask.
const symbol = read("app-icon.svg").replace(/<rect[^>]*\/>/, "");
const adaptive = (inner) =>
  `<group android:pivotX="256" android:pivotY="256" android:scaleX="0.75" android:scaleY="0.75" android:translateX="-4.5" android:translateY="-4.5">${inner}</group>`;
write(
  "app/src/main/res/drawable/ic_launcher_foreground.xml",
  vector(symbol, { width: 108, height: 108, inner: adaptive }),
);

// Themed (monochrome) icon: one colour, the keyhole cut out of the circle.
const mono = symbol
  .replace(/<circle[^>]*\/>/, "")
  .replace(
    /<path d="(M315[^"]*)" fill="[^"]*"\/>/,
    (_, keyhole) => `<path d="${circle(294, 294, 122)} ${keyhole}" fill="#FFFFFF"/>`,
  );
write(
  "app/src/main/res/drawable/ic_launcher_monochrome.xml",
  vector(mono, {
    width: 108,
    height: 108,
    colour: "#FFFFFF",
    inner: (b) => adaptive(b.replace('<path android:pathData="M172', '<path android:fillType="evenOdd" android:pathData="M172')),
  }),
);
